BOT_NAME = "ЧИЛИПИЗДРИК"

# Команды
COMMANDS = {
    'name.change': 'change_name',
    'help': 'show_help',
    'exit': 'exit_bot',
}

def show_help():
    print(f"\n[SYSTEM] Доступные команды:")
    print("  name.change — сменить имя бота")
    print("  help        — показать это сообщение")
    print("  exit        — выйти из программы\n")

def get_response(text):
    text_upper = text.upper()
    for key, data in RESPONSES.items():
        if text_upper in {t.upper() for t in data['triggers']}:
            return random.choice(data['replies'])
    return None

def startup():
    global BOT_NAME
    print("ЧИЛИПИЗДРИК БОТ v2.0")
    time.sleep(0.5)
    print("РАЗРАБ: Рам#3977")
    time.sleep(0.5)
    print("ПРИЯТНОГО ИСПОЛЬЗОВАНИЯ <3")
    time.sleep(0.5)
    input("//НАЖМИТЕ ENTER//\n")
    # Очистка экрана через пустые строки
    print("\n" * 30)

def main():
    global BOT_NAME
    startup()

    while True:
        try:
            answer = input('[ТЫ]: ').strip()
        except (KeyboardInterrupt, EOFError):
            print(f"\n[{BOT_NAME}]: пока пока")
            break

        # Обработка команд
        if answer.lower() == 'name.change':
            BOT_NAME = input("[SYSTEM] Введите имя бота: ").strip() or BOT_NAME
            print(f"[SYSTEM] Применено имя: {BOT_NAME}")
            continue

        if answer.lower() == 'help':
            show_help()
            continue

        if answer.lower() == 'exit':
            print(f"[{BOT_NAME}]: пока пока")
            break

        # Пустое сообщение
        if not answer:
            print(f"[{BOT_NAME}]: {random.choice(NOTEXT_REPLIES)}")
            continue

        # Поиск ответа
        response = get_response(answer)
        if response:
            print(f"[{BOT_NAME}]: {response}")
        else:
            print(f"[{BOT_NAME}]: {random.choice(OTHER)}")

if __name__ == "__main__":
    main()
